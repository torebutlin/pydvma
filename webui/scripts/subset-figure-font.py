"""Build the embedded figure font from STIX Two Text (SIL OFL 1.1).

Run from the repo root with no arguments:

    python webui/scripts/subset-figure-font.py

Writes, under webui/src/lib/export/fonts/: PydvmaFigureSerif.ttf (the Regular
instance of the variable font, subset and renamed), OFL.txt (licence plus the
font's copyright) and figureFontMetrics.ts (advances for text measurement).
Source: https://github.com/stipub/stixfonts (release 2.13).
"""
import json
import os
import sys

import matplotlib
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

SRC = '/System/Library/Fonts/Supplemental/STIXTwoText.ttf'
OUT = os.path.join('webui', 'src', 'lib', 'export', 'fonts')
FAMILY = 'Pydvma Figure Serif'
RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x100, 0x17F), (0x370, 0x3FF),
          (0x2000, 0x206F), (0x2070, 0x209F), (0x2100, 0x214F),
          (0x2190, 0x2193), (0x2200, 0x22FF)]


def main():
    if not os.path.exists(SRC):
        print(f'Missing {SRC}. Get STIX Two Text from '
              'https://github.com/stipub/stixfonts (release 2.13).')
        sys.exit(1)
    os.makedirs(OUT, exist_ok=True)
    font = instancer.instantiateVariableFont(TTFont(SRC), {'wght': 400})
    opts = subset.Options()
    opts.hinting = False
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=[c for a, b in RANGES for c in range(a, b + 1)])
    sub.subset(font)

    name = font['name']
    for nid, text in ((1, FAMILY), (16, FAMILY), (2, 'Regular'), (17, 'Regular'),
                      (4, FAMILY + ' Regular'), (6, 'PydvmaFigureSerif-Regular'),
                      (10, 'Subset of STIX Two Text 2.13 (Regular instance), '
                           'renamed under the SIL OFL 1.1.')):
        name.names = [n for n in name.names if n.nameID != nid]
        name.setName(text, nid, 3, 1, 0x409)
        name.setName(text, nid, 1, 0, 0)
    ttf = os.path.join(OUT, 'PydvmaFigureSerif.ttf')
    font.save(ttf)

    copyright_ = name.getDebugName(0) or ''
    lic_path = os.path.join(matplotlib.get_data_path(), 'fonts/ttf/LICENSE_STIX')
    lines = open(lic_path, encoding='utf8').read().splitlines()
    start = next(i for i, l in enumerate(lines)
                 if l.strip().startswith('SIL OPEN FONT LICENSE Version 1.1'))
    header = (f'PydvmaFigureSerif.ttf is a subset of STIX Two Text 2.13 (the Regular\n'
              f'instance of {SRC}), renamed "{FAMILY}" as the OFL requires of a\n'
              f'modified version. Upstream: https://github.com/stipub/stixfonts\n\n')
    with open(os.path.join(OUT, 'OFL.txt'), 'w', encoding='utf8') as f:
        f.write(header + copyright_ + '\n\n' + '\n'.join(lines[start:]) + '\n')

    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    advances = {str(cp): hmtx[g][0] for cp, g in sorted(cmap.items())}
    metrics = {'family': FAMILY, 'unitsPerEm': font['head'].unitsPerEm,
               'ascender': font['hhea'].ascent, 'descender': -font['hhea'].descent,
               'advances': advances}
    with open(os.path.join(OUT, 'figureFontMetrics.ts'), 'w', encoding='utf8') as f:
        f.write('// Generated by webui/scripts/subset-figure-font.py. Do not edit.\n'
                'export const FIGURE_FONT_METRICS: { family: string; unitsPerEm: number; '
                'ascender: number; descender: number; advances: Record<string, number> } = '
                + json.dumps(metrics) + ';\n')
    print(f'{ttf}: {os.path.getsize(ttf)} bytes, {len(cmap)} glyphs mapped')


main()
